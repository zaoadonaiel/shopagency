-- ---------- The claim lock ----------
-- One UPDATE decides the winner. Postgres row locking means that when two contractors
-- claim at the same instant, the second UPDATE waits, re-checks status='open', finds
-- 'claimed' and matches nothing. Returns the claimed row, or no rows if the claim lost.
create function public.claim_order(p_order_id bigint, p_user_id uuid)
returns setof public.orders
language sql
security invoker
set search_path = ''
as $$
  update public.orders o
     set status = 'claimed',
         contractor_id = p_user_id,
         claimed_at = now(),
         due_at = now() + make_interval(hours => o.turnaround_hours),
         reminders_sent = 0
   where o.id = p_order_id
     and o.status = 'open'
     and o.dispute = false
     and not exists (
       select 1 from public.exclusions e
        where e.order_id = p_order_id and e.contractor_id = p_user_id
     )
  returning o.*;
$$;

-- Only the server (service role) may call it. Otherwise any signed-in user could
-- call it through the REST API and claim a job for anyone.
revoke execute on function public.claim_order(bigint, uuid) from public, anon, authenticated;
grant execute on function public.claim_order(bigint, uuid) to service_role;

-- ---------- Row level security ----------

alter table public.profiles enable row level security;
alter table public.packages enable row level security;
alter table public.orders enable row level security;
alter table public.exclusions enable row level security;
alter table public.messages enable row level security;

-- Explicit grants, so this works whether or not the project "automatically exposes new tables".
-- The server's service role needs full access; signed-in users get read access, narrowed by the policies below.
grant usage on schema public to service_role, authenticated;
grant all on public.profiles, public.packages, public.orders, public.exclusions, public.messages to service_role;
grant usage, select on all sequences in schema public to service_role;
grant select on public.profiles, public.packages, public.orders, public.exclusions, public.messages to authenticated;

-- No policies for anon: logged-out browsers can read nothing.
-- Signed-in users can read only their own rows, and cannot write anything directly.
revoke all on public.profiles, public.packages, public.orders, public.exclusions, public.messages from anon;
revoke insert, update, delete, truncate on public.profiles, public.packages, public.orders, public.exclusions, public.messages from authenticated;

create policy "read own profile" on public.profiles
  for select to authenticated
  using (id = (select auth.uid()));

create policy "read active packages" on public.packages
  for select to authenticated
  using (active);

create policy "read own orders" on public.orders
  for select to authenticated
  using (buyer_id = (select auth.uid()) or contractor_id = (select auth.uid()));

create policy "read own exclusions" on public.exclusions
  for select to authenticated
  using (contractor_id = (select auth.uid()));

create policy "read messages on own orders" on public.messages
  for select to authenticated
  using (exists (
    select 1 from public.orders o
     where o.id = messages.order_id
       and (o.buyer_id = (select auth.uid()) or o.contractor_id = (select auth.uid()))
  ));

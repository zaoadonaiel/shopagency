-- Agency School Shop: initial schema (ported from the SQLite schema in the old src/db.js).
-- Money is always integer cents. Dates are always timestamptz.
-- The Express server uses the service role key, which bypasses row level security.
-- The RLS policies below are a second layer: a signed-in user holding only the anon key
-- and their own JWT can read their own rows and nothing else, and can write nothing.

-- ---------- Tables ----------

-- One row per Supabase Auth user. Email is copied here so the server can list admins,
-- contractors and payout recipients without paging through the Auth admin API.
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null unique,
  name text not null,
  role text not null check (role in ('buyer', 'contractor', 'admin')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.packages (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null,
  price_cents integer not null,
  contractor_pct integer not null default 40,
  active boolean not null default true
);

create table public.orders (
  id bigint generated by default as identity primary key,
  buyer_id uuid not null constraint orders_buyer_id_fkey references public.profiles (id),
  package_id bigint not null references public.packages (id),
  package_name text not null,
  status text not null default 'pending_payment'
    check (status in ('pending_payment', 'open', 'claimed', 'ready', 'approved', 'refunded', 'cancelled')),
  price_cents integer not null,
  contractor_pct integer not null,
  turnaround text not null check (turnaround in ('24h', '3d')),
  turnaround_hours integer not null,
  business_name text not null,
  domain text,
  avada_code text not null,
  notes text,
  created_at timestamptz not null default now(),
  paid_at timestamptz,
  stripe_session_id text,
  stripe_payment_intent text,
  card_fee_cents integer not null default 0,
  open_since timestamptz,
  unclaimed_alerted_at timestamptz,
  contractor_id uuid constraint orders_contractor_id_fkey references public.profiles (id),
  claimed_at timestamptz,
  due_at timestamptz,
  reminders_sent integer not null default 0,
  buyer_reminded boolean not null default false,
  site_url text,
  admin_url text,
  wp_username text,
  pages_built integer,
  done_at timestamptz,
  auto_approve_at timestamptz,
  approved_at timestamptz,
  contractor_pay_cents integer not null default 0,
  paid_out_at timestamptz,
  dispute boolean not null default false,
  hold_reason text,
  refunded_at timestamptz
);

create table public.exclusions (
  order_id bigint not null references public.orders (id),
  contractor_id uuid not null constraint exclusions_contractor_id_fkey references public.profiles (id),
  reason text,
  created_at timestamptz not null default now(),
  primary key (order_id, contractor_id)
);

create table public.messages (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders (id),
  sender_id uuid not null constraint messages_sender_id_fkey references public.profiles (id),
  body text not null,
  created_at timestamptz not null default now()
);

create index idx_orders_status on public.orders (status);
create index idx_orders_buyer on public.orders (buyer_id);
create index idx_orders_contractor on public.orders (contractor_id);
create index idx_messages_order on public.messages (order_id);
create index idx_exclusions_contractor on public.exclusions (contractor_id);

